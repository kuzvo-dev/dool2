/** 두 앱 모두에 있는 아이콘 이름 */
export type IdeaIcon =
  | 'goal'
  | 'cart'
  | 'box'
  | 'star'
  | 'card'
  | 'place'
  | 'plane'
  | 'ticket'
  | 'note'
  | 'mail'
  | 'sun'
